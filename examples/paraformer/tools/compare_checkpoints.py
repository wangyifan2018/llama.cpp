#!/usr/bin/env python3
"""Score two Paraformer checkpoints on the same fixtures, with the same rule.

The zh checkpoint (vocab 8404) and the en checkpoint (vocab 10020) both run in
this engine; what changes is the token convention and, in principle, the
accuracy. Comparing them is easy to get wrong in three specific ways, each of
which this script removes:

  1. Different fixtures. Both sides read the same manifest and the same wav
     files, so a difference cannot come from the audio.
  2. Different scoring. Rates come from eval_cer.norm_zh / norm_en, the same
     functions the cabin table in PRODUCTION.md uses. norm_en returns a string,
     so it must be split into words; scoring its characters would report CER
     while calling it WER.
  3. Different stitching. The engine assembles both checkpoints through one
     shared function, so a gap here is a model gap, not a formatting gap.

A voice that is not native for the language of a clip makes the clip a
measurement of the synthesizer, not the engine, so voice_languages.tsv decides
which voices are eligible at all.

    python3 compare_checkpoints.py \
        --zh paraformer-zh-q8_0.gguf --en paraformer-en-f32.gguf \
        --fingerprint <sha256 of zh weights> \
        --dir voices/eddy --dir voices/rocko --out compare.json
"""

import argparse
import json
import os
from pathlib import Path
import statistics
import subprocess
import sys
import tempfile
import time

sys.path.insert(0, str(Path(__file__).resolve().parents[2] / "x-asr" / "tools"))
from eval_cer import edit_distance, norm_en, norm_zh  # noqa: E402

HERE = Path(__file__).resolve().parent


def read_manifest(path):
    rows = []
    for line in Path(path).read_text(encoding="utf-8").splitlines():
        if not line.strip() or line.startswith("#"):
            continue
        fields = line.split("\t")
        if len(fields) < 3:
            continue
        rows.append((fields[0], fields[1], fields[2]))
    return rows


def load_voice_languages(path=HERE / "voice_languages.tsv"):
    """voice -> {"zh": bool, "en": bool}. Missing file means allow everything."""
    table = {}
    p = Path(path)
    if not p.exists():
        return table
    for line in p.read_text(encoding="utf-8-sig").splitlines():
        if not line.strip() or line.startswith("#"):
            continue
        fields = line.split("\t")
        if len(fields) < 3 or fields[0] == "voice":
            continue
        table[fields[0]] = {"zh": fields[1].strip() == "yes", "en": fields[2].strip() == "yes"}
    return table


def dir_voice(path):
    """Fixture dir -> voice name, from the directory basename.

    `voices/eddy`, `/tmp/voice-eddy` and `/tmp/voice-Eddy` all mean Eddy, so a
    sweep generated by gen_voice_fixtures.py can be scored where it lands.
    """
    name = Path(path).resolve().name
    if name.startswith("voice-"):
        name = name[len("voice-"):]
    for known in ("Tingting", "Meijia", "Sinji", "Sandy", "Eddy", "Rocko",
                  "Shelley", "Reed", "Grandma", "Grandpa", "Flo"):
        if name.lower() == known.lower():
            return known
    return name


def score_ref(ref, hyp, lang):
    """(errors, units). norm_zh keeps Latin letters, norm_en needs splitting."""
    if lang == "zh":
        r, h = norm_zh(ref), norm_zh(hyp)
        return edit_distance(r, h), len(r)
    r, h = norm_en(ref), norm_en(hyp)
    rw, hw = r.split(), h.split()
    return edit_distance(rw, hw), len(rw)


def run_cli(binary, model, wavs, quiet=True, timeout=1800):
    cmd = [binary, model, *map(str, wavs)]
    if quiet:
        cmd.append("--quiet")
    env = dict(os.environ)
    proc = subprocess.run(cmd, capture_output=True, text=True, timeout=timeout, env=env)
    out = {}
    for line in proc.stdout.splitlines():
        fields = line.split("\t")
        if len(fields) < 4:
            continue
        out[Path(fields[0]).stem] = fields[-1]
    if not out:
        raise SystemExit(f"no transcripts from {model}\n{proc.stderr[-2000:]}")
    return out


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--zh", required=True, help="zh checkpoint gguf")
    ap.add_argument("--en", required=True, help="en checkpoint gguf")
    ap.add_argument("--binary", default=str(Path(__file__).resolve().parents[3] /
                                            "build-pf-host" / "bin" / "llama-paraformer"))
    ap.add_argument("--dir", action="append", required=True, help="fixture dir with manifest.tsv")
    ap.add_argument("--out", default=None)
    args = ap.parse_args()

    vlang = load_voice_languages()
    report = {}
    for d in args.dir:
        d = Path(d)
        voice = dir_voice(d)
        rows = read_manifest(d / "manifest.tsv")
        eligible = vlang.get(voice)
        for tag, model in (("zh-ckpt", args.zh), ("en-ckpt", args.en)):
            wavs = [d / name for name, _, _ in rows]
            missing = [w for w in wavs if not w.exists()]
            if missing:
                raise SystemExit(f"missing wav: {missing[0]}")
            hyps = run_cli(args.binary, model, wavs)
            per = []
            for name, lang, ref in rows:
                hyp = hyps.get(Path(name).stem)
                if hyp is None:
                    raise SystemExit(f"no transcript for {name} from {model}")
                if eligible is not None and not eligible.get(lang, False):
                    per.append({"name": name, "lang": lang, "ref": ref, "hyp": hyp,
                                "excluded": "not a native voice for this language"})
                    continue
                err, units = score_ref(ref, hyp, lang)
                per.append({"name": name, "lang": lang, "ref": ref, "hyp": hyp,
                            "errors": err, "units": units})
            entry = report.setdefault(f"{voice}/{tag}", {"voice": voice, "ckpt": tag,
                                                         "dir": str(d), "per_clip": per})
            entry.update(summarise(per))
    text = json.dumps(report, ensure_ascii=False, indent=1)
    if args.out:
        Path(args.out).write_text(text, encoding="utf-8")
        print(print_table(report))
        print(f"\nwrote {args.out}")
    else:
        print(text)


def summarise(per):
    out = {}
    for lang in ("zh", "en"):
        rows = [r for r in per if r["lang"] == lang and "errors" in r]
        err = sum(r["errors"] for r in rows)
        units = sum(r["units"] for r in rows)
        out[lang] = {"clips": len(rows), "errors": err, "units": units,
                     "rate": (100.0 * err / units) if units else None}
    return out


def print_table(report):
    lines = []
    header = f"{'voice':10s} {'ckpt':8s} {'zh CER':>9s} {'zh n':>5s} {'en WER':>9s} {'en n':>5s}"
    lines.append(header)
    lines.append("-" * len(header))
    for key in sorted(report):
        e = report[key]
        zh, en = e["zh"], e["en"]
        zr = f"{zh['rate']:.2f}%" if zh["rate"] is not None else "-"
        er = f"{en['rate']:.2f}%" if en["rate"] is not None else "-"
        lines.append(f"{e['voice']:10s} {e['ckpt']:8s} {zr:>9s} {zh['units']:5d} {er:>9s} {en['units']:5d}")
    return "\n".join(lines)


if __name__ == "__main__":
    main()