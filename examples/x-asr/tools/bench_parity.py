#!/usr/bin/env python3
"""Summarise one same-arrival run: latency, widths, placement, transcript parity.

Reads the directory written by `bench_load_matrix.py`:

    config.json       run metadata, inputs, arm command lines
    <arm>.jsonl       one record per request per round
    <arm>.log         server stderr for that arm

and writes `summary.md` next to them. Percentiles are always over requests.
Transcript parity is reported per (scenario, round, session): first across the
GGUF arms, then ONNX against GGUF as a separate list, because the INT8 export
is a different quantisation and is not expected to match.
"""

import argparse
import json
import os
import re
import statistics
import sys

SCENARIO_ORDER = ["single", "aligned4", "stagger4", "mixed4", "burst4", "vadburst"]


def pct(values, q):
    if not values:
        return float("nan")
    ordered = sorted(values)
    if len(ordered) == 1:
        return ordered[0]
    pos = (len(ordered) - 1) * q / 100.0
    lo = int(pos)
    hi = min(lo + 1, len(ordered) - 1)
    return ordered[lo] + (ordered[hi] - ordered[lo]) * (pos - lo)


def load_rows(path):
    rows = []
    if not os.path.exists(path):
        return rows
    with open(path) as fh:
        for line in fh:
            line = line.strip()
            if line:
                rows.append(json.loads(line))
    return rows


def load_text(path):
    if not os.path.exists(path):
        return ""
    with open(path, errors="replace") as fh:
        return fh.read()


def width_histogram(log):
    hist = {}
    for n in re.findall(r"xasr-batch size=(\d+)", log):
        hist[int(n)] = hist.get(int(n), 0) + 1
    return hist


def placement(log):
    out = []
    seen = set()
    for tag in ("encoder", "joiner"):
        for line in re.findall(r"xasr: %s \S.*" % tag, log):
            if line not in seen:
                seen.add(line)
                out.append(line)
    return out


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--dir", required=True)
    parser.add_argument("--out", default=None)
    args = parser.parse_args()

    root = args.dir
    config = json.load(open(os.path.join(root, "config.json"))) if \
        os.path.exists(os.path.join(root, "config.json")) else {}
    arms = [a["name"] for a in config.get("arms", [])]
    if not arms:
        arms = sorted(f[:-6] for f in os.listdir(root) if f.endswith(".jsonl"))
    gguf_arms = [a for a in arms if a.startswith("htp") or a.startswith("gguf")]
    onnx_arms = [a for a in arms if a.startswith("onnx")]

    data = {a: load_rows(os.path.join(root, a + ".jsonl")) for a in arms}
    logs = {a: load_text(os.path.join(root, a + ".log")) for a in arms}

    lines = []
    add = lines.append
    add("# Same-arrival comparison: %s" % config.get("run_id", os.path.basename(root.rstrip("/"))))
    add("")
    add("Generated by `tools/bench_parity.py` from `%s`." % root)
    add("")
    if config:
        dev = config.get("device", {})
        add("- Started: %s" % config.get("started_at", "?"))
        add("- Git revision: `%s`%s" % (config.get("git_rev", "?"),
                                        " (dirty: %s)" % ", ".join(config["git_dirty"])
                                        if config.get("git_dirty") else ""))
        add("- Device: `%s`, %s, Android %s" % (dev.get("serial", "?"), dev.get("soc", "?"),
                                               dev.get("android", "?")))
        add("- Rounds per scenario: %s. Every percentile below is over requests." %
            config.get("rounds", "?"))
        add("- Remote package: `%s`, port %s, client on the host through ADB forward." %
            (config.get("remote", "?"), config.get("port", "?")))
        add("")
        add("## Inputs")
        add("")
        add("| Input | SHA-256 |")
        add("|---|---|")
        model = config.get("model", {})
        if model:
            add("| `%s` | `%s` |" % (os.path.basename(model.get("path", "?")),
                                     model.get("sha256", "?")))
        for name, info in (config.get("fixtures") or {}).items():
            add("| `%s` | `%s` |" % (name, info.get("sha256", "?")))
        for name, info in (config.get("binaries") or {}).items():
            add("| `%s` | `%s` |" % (name, info.get("sha256", "?")))
        add("")
        add("## Arms")
        add("")
        add("| Arm | Batch cap | Command line |")
        add("|---|---:|---|")
        for arm in config.get("arms", []):
            add("| `%s` | %s | `%s` |" % (arm["name"],
                                          "-" if arm.get("batch_cap") is None else arm["batch_cap"],
                                          arm.get("argv", "")))
        add("")
        for arm in config.get("arms", []):
            if arm.get("env"):
                add("- `%s` env: `%s`" % (arm["name"], arm["env"]))
        add("")

    if not any(data.values()):
        add("No request records were found.")
        open(args.out or os.path.join(root, "summary.md"), "w").write("\n".join(lines) + "\n")
        print("\n".join(lines))
        return

    seen = []
    for arm in arms:
        for r in data[arm]:
            if r["scenario"] not in seen:
                seen.append(r["scenario"])
    scenarios = [s for s in SCENARIO_ORDER if s in seen] + [s for s in seen if s not in SCENARIO_ORDER]

    add("## Endpoint to final, ms")
    add("")
    header = "| Arm | Scenario | N | Errors | p50 | p95 | p99 | max | x real time |"
    add(header)
    add("|---|---|---:|---:|---:|---:|---:|---:|---:|")
    for arm in arms:
        for scenario in scenarios:
            cells = [r for r in data[arm] if r["scenario"] == scenario]
            ok = [r for r in cells if "endpoint_to_final_ms" in r]
            vals = [r["endpoint_to_final_ms"] for r in ok]
            if not vals:
                add("| `%s` | %s | %d | %d | - | - | - | - | - |"
                    % (arm, scenario, len(cells), len(cells) - len(ok)))
                continue
            # Audio seconds delivered per wall second, over each round's own span.
            xrt = []
            for rnd in sorted({r["round"] for r in ok}):
                group = [r for r in ok if r["round"] == rnd]
                span = max(r["t_done_ms"] for r in group) / 1000.0
                audio = sum(r["audio_ms"] for r in group) / 1000.0
                if span > 0:
                    xrt.append(audio / span)
            add("| `%s` | %s | %d | %d | %.1f | %.1f | %.1f | %.1f | %s |"
                % (arm, scenario, len(vals), len(cells) - len(ok), pct(vals, 50), pct(vals, 95),
                   pct(vals, 99), max(vals),
                   "%.2f" % statistics.median(xrt) if xrt else "-"))
    add("")
    add("`x real time` is audio seconds delivered per wall second inside one round, "
        "so `RTF = 1 / x`. It describes the arrival pattern, not engine throughput.")
    add("")

    add("## Encoder batch widths")
    add("")
    add("| Arm | Widths seen (dispatches) | Placement |")
    add("|---|---|---|")
    caps = {a["name"]: a.get("batch_cap") for a in config.get("arms", [])}
    for arm in arms:
        hist = width_histogram(logs[arm])
        if hist:
            widths = ", ".join("%d x B=%d" % (c, w) for w, c in sorted(hist.items()))
        elif arm.startswith("onnx"):
            widths = "not instrumented"
        elif caps.get(arm) is None:
            widths = "B=1 only (no batch log)"
        else:
            widths = "no dispatch seen"
        place = "<br>".join("`%s`" % p for p in placement(logs[arm]))
        if not place:
            place = "not instrumented (sherpa-onnx)" if arm.startswith("onnx") else "n/a"
        add("| `%s` | %s | %s |" % (arm, widths, place))
    add("")

    # Transcript parity. Key is (scenario, round, session); a rep that errors on
    # one arm is skipped rather than counted as a mismatch.
    def keyed(arm):
        out = {}
        for r in data[arm]:
            if "endpoint_to_final_ms" in r:
                out[(r["scenario"], r["round"], r["session"])] = r.get("text", "")
        return out

    texts = {a: keyed(a) for a in arms}
    add("## Transcript parity")
    add("")
    total_errors = sum(len([r for r in data[a] if "endpoint_to_final_ms" not in r]) for a in arms)
    add("- Recorded %d requests across %d arms, %d without a final text."
        % (sum(len(data[a]) for a in arms), len(arms), total_errors))
    if len(arms) == 1:
        add("- One arm only, so there is nothing to compare across engines.")
    if len(gguf_arms) > 1:
        ref = texts[gguf_arms[0]]
        shared = [k for k in ref if all(k in texts[a] for a in gguf_arms)]
        diffs = [(k, ref[k], {a: texts[a][k] for a in gguf_arms[1:]}) for k in shared
                 if any(texts[a][k] != ref[k] for a in gguf_arms[1:])]
        add("- GGUF arms (%s): %d of %d requests identical across every width."
            % (", ".join(gguf_arms), len(shared) - len(diffs), len(shared)))
        for k, base, others in diffs[:10]:
            add("  - `%s` round %s session %d: `%s` vs %s" %
                (k[0], k[1], k[2], base, ", ".join("%s=`%s`" % i for i in others.items())))
    if onnx_arms and gguf_arms:
        ref_arm = gguf_arms[0]
        ref, onnx = texts[ref_arm], texts[onnx_arms[0]]
        shared = [k for k in ref if k in onnx]
        diffs = [k for k in shared if ref[k] != onnx[k]]
        add("")
        add("- ONNX vs GGUF (%s against `%s`): %d of %d requests differ."
            % (onnx_arms[0], ref_arm, len(diffs), len(shared)))
        add("  These are separate exports and quantisations, so a difference is expected; "
            "they are listed so latency can be read without mixing the two qualities.")
        pairs = {}
        for k in diffs:
            pairs.setdefault((onnx[k], ref[k]), []).append(k)
        for (onnx_text, gguf_text), keys in sorted(pairs.items(), key=lambda kv: -len(kv[1])):
            where = ", ".join(sorted({"%s r%d s%d" % k for k in keys[:3]}))
            more = "" if len(keys) <= 3 else " (+%d more)" % (len(keys) - 3)
            add("  - %d requests, %s%s: ONNX `%s` / GGUF `%s`"
                % (len(keys), where, more, onnx_text, gguf_text))
        per_scenario = {}
        for k in shared:
            per_scenario.setdefault(k[0], [0, 0])
            per_scenario[k[0]][1] += 1
            if ref[k] != onnx[k]:
                per_scenario[k[0]][0] += 1
        add("  - Differences by scenario: " + ", ".join(
            "%s %d/%d" % (s, v[0], v[1]) for s, v in sorted(per_scenario.items())))
    add("")

    add("## Reading this run")
    add("")
    add("- Every arm ran the same WAVs, packet size, tail padding and client; only the "
        "engine changed.")
    if config.get("interleaved"):
        add("- Rounds are interleaved across arms, so slow device drift hits every arm "
            "and the per-arm medians are comparable.")
    else:
        add("- Each arm ran all its rounds back to back, so drift inside the run is not "
            "evenly spread; re-run interleaved before trusting a change under 10 percent.")
    add("- A round is one execution of the scenario; N is requests, not rounds. Three "
        "rounds of a four-session scenario give N=12.")
    add("")

    text = "\n".join(lines) + "\n"
    target = args.out or os.path.join(root, "summary.md")
    with open(target, "w") as fh:
        fh.write(text)
    print(text)
    print("written:", target, file=sys.stderr)


if __name__ == "__main__":
    main()
